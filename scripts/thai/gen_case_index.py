"""Write lib/caseIndex.ts: every case, in Thai when a Thai file exists, else the English source."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
en = sorted(p.stem for p in (ROOT / "public/locales/en").glob("case_*.json"))
th = {p.stem for p in (ROOT / "public/locales/th").glob("case_*.json")}
lines = ["// Generated by scripts/thai/gen_case_index.py. Do not edit by hand.", ""]
for i, c in enumerate(en):
    lang = "th" if c in th else "en"
    lines.append(f'import c{i} from "../public/locales/{lang}/{c}.json";')
lines += ["", "export const CASE_DATA: Record<string, any> = {"]
lines += [f'  "{c}": c{i},' for i, c in enumerate(en)]
lines += ["};", "", f"export const THAI_CASES = {len(th & set(en))};", ""]
(ROOT / "lib/caseIndex.ts").write_text("\n".join(lines))
print(f"{len(en)} cases, {len(th & set(en))} in Thai")
