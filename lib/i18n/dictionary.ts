export type DictKey = keyof typeof DICTIONARY;

export function tr(key: DictKey | string, lang: Lang, vars?: Record<string, string | number>): string {
  const entry = (DICTIONARY as Record<string, Entry>)[key];
  let out = entry ? entry[lang] ?? entry.en : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

/** Audit helper: returns keys missing a Thai string (should always be empty). */
export function auditThai(): string[] {
  return Object.entries(DICTIONARY).filter(([, v]) => !v.th).map(([k]) => k);
}
