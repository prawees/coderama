export function icon(name: string): PixelGrid {
  const rows = ICONS[name] ?? ICONS.heart;
  const w = Math.max(...rows.map((r) => r.length));
  const g = new PixelGrid(w, rows.length);
  g.stamp(0, 0, rows, K);
  return g;
}

